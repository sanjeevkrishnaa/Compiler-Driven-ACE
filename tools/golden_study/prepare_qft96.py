#!/usr/bin/env python3
"""Generate auditable QFT-96 placements and mesh/torus routes.

The benchmark is generated by the vendored qmap QFT generator, using the same
mapper CLI seed derivation as the historical QFT-96 comparison. One placement
is reused for both topologies so the topology comparison holds migration
endpoints fixed. Routing reliabilities use the *derived* mapper seed, which is
the seed actually passed to qmap's mesh architecture during placement.
"""
from __future__ import annotations

import argparse
import csv
import json
from dataclasses import asdict
from pathlib import Path

import numpy as np

from qmap.architecture.reliability import ReliabilityBand
from qmap.experiments.runner import prepare_trial, run_trial
from qmap.placement.base import PlacerConfig
from qmap.rng import SeedSequence
from qmap.validation import validate_partition

from tools.mapper_ace.adapter import import_legacy_request_file
from tools.mapper_ace.export import export
from tools.mapper_ace.placement_contract import build_architecture, contract

from .map_inputs import canonical_hash, sha256


def load_contract(path: Path) -> dict:
    spec = json.loads(path.read_text(encoding="utf-8"))
    if spec.get("schema") != "qft96-mapping-contract-v1":
        raise ValueError("expected qft96-mapping-contract-v1")
    if spec["benchmark"] != "qft" or spec["width"] != 96:
        raise ValueError("this exporter requires the declared 96-qubit QFT generator")
    if spec["routing"].get("torus") != ["dijkstra"]:
        raise ValueError("torus routing must be Dijkstra only")
    if spec["seed_derivation"] != "mapper-cli-trial-v1":
        raise ValueError("unsupported seed derivation")
    return spec


def circuit_hash(setup) -> str:
    circuit = setup.sliced.circuit
    return canonical_hash({
        "name": circuit.name,
        "n_qubits": circuit.n_qubits,
        "gates": [asdict(gate) for gate in circuit.gates],
    })


def verify_replay(requests: Path, payload: dict) -> None:
    architecture = build_architecture(
        tuple(payload["dimensions"]), payload["qubits_per_core"],
        payload["seed"], payload["reliability_min"],
        payload["reliability_max"], payload["topology"],
    )
    replay, _ = import_legacy_request_file(requests, architecture)
    expected = np.asarray(payload["assignments"], dtype=np.int32)
    actual = replay.assignments
    if actual.shape[0] < expected.shape[0]:
        actual = np.vstack((actual, np.repeat(actual[-1:], expected.shape[0] - actual.shape[0], axis=0)))
    if (not np.array_equal(actual, expected)
            or not np.array_equal(replay.initial_assignment, payload["initial_assignment"])):
        raise ValueError(f"route replay differs from placement: {requests}")


def run(root: Path, spec: dict) -> None:
    rows = []
    expected_circuit_hash = None
    mapping = spec["mapping"]
    band = ReliabilityBand(float(mapping["reliability_min"]), float(mapping["reliability_max"]))
    for mapping_seed in spec["mapping_seeds"]:
        derived = SeedSequence.from_seed(mapping_seed).for_trial(
            spec["benchmark"], "mesh", mapping["grid"], 0,
        )
        setup = prepare_trial(
            grid=mapping["grid"], benchmark=spec["benchmark"], seed=derived,
            reliability_band=band, qubits_per_core=mapping["data_qubits_per_core"],
            reserved_ancilla=mapping["reserved_initial_slots_per_core"],
            topology="mesh", width=spec["width"],
        )
        digest = circuit_hash(setup)
        if expected_circuit_hash is None:
            expected_circuit_hash = digest
        elif digest != expected_circuit_hash:
            raise ValueError("QFT circuit changed between mapping seeds")
        result = run_trial(
            setup, mapping["placer"],
            PlacerConfig(initial_placement=mapping["initial_placement"]),
            benchmark=spec["benchmark"], reliability_band=band.label,
            keep_partition=True,
        )
        partition = result.partition
        if partition is None or result.n_qubits != 96:
            raise ValueError("QFT-96 partition is missing or has the wrong width")
        validation = validate_partition(partition, setup.sliced, setup.architecture)
        if not validation.is_complete:
            raise ValueError(f"seed {mapping_seed}: unplaced operations remain")
        placement_signature = canonical_hash({
            "initial": partition.initial_assignment.tolist(),
            "assignments": partition.assignments.tolist(),
        })
        for topology, policies in spec["routing"].items():
            target = root / "traces" / "placements" / topology / mapping["placer"] / "qft96" / f"seed_{mapping_seed}"
            placement = target / "placement.json"
            if target.exists():
                raise FileExistsError(f"refusing to replace an existing placement: {target}")
            target.mkdir(parents=True)
            payload = contract(
                partition, dimensions=tuple(setup.architecture.dimensions),
                qubits_per_core=mapping["data_qubits_per_core"], seed=derived.seed,
                reliability_min=band.low, reliability_max=band.high,
                topology=topology,
                provenance={
                    "kind": "qmap-generated-qft96", "mapper_partition_exact": True,
                    "mapping_seed": mapping_seed, "derived_mapper_seed": derived.seed,
                    "derived_seed_path": derived.path, "circuit_sha256": digest,
                    "placement_signature": placement_signature,
                    "placement_source_topology": "mesh",
                    "mapping_record": result.as_record(),
                    "mapping_config": mapping,
                    "uncolocated_operations": validation.uncolocated_operations,
                    "maximum_data_occupancy": validation.max_occupancy,
                },
            )
            placement.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
            for policy in policies:
                route = target / "routes" / policy
                manifest = export(placement, route, policy)
                requests = route / "requests.txt"
                verify_replay(requests, payload)
                rows.append({
                    "topology": topology, "mapping_algorithm": mapping["placer"],
                    "workload": "qft96", "mapping_seed": mapping_seed,
                    "route_policy": policy,
                    "placement_sha256": sha256(placement),
                    "migration_trace_sha256": sha256(route / "migrations.jsonl"),
                    "request_trace_sha256": sha256(requests),
                    "logical_migrations": manifest["placement"]["logical_migrations"],
                    "physical_hops": manifest["placement"]["physical_hops"],
                    "timeslices": manifest["placement"]["timeslices"],
                    "qubits": manifest["placement"]["qubits"],
                    "valid": True,
                })
            print(f"mapped seed={mapping_seed} topology={topology} routes={','.join(policies)}", flush=True)
    validation_dir = root / "validation"
    validation_dir.mkdir(parents=True, exist_ok=True)
    audit = validation_dir / "mapping_audit.csv"
    with audit.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    record = {
        "schema": "qft96-mapping-audit-v1", "route_count": len(rows),
        "all_valid": all(row["valid"] and row["qubits"] == 96 for row in rows),
        "mapping_seeds": spec["mapping_seeds"],
        "circuit_sha256": expected_circuit_hash,
        "mapping_audit_sha256": sha256(audit),
    }
    (validation_dir / "mapping_record.json").write_text(
        json.dumps(record, indent=2, sort_keys=True) + "\n", encoding="utf-8",
    )
    print(json.dumps(record, indent=2, sort_keys=True))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    args = parser.parse_args()
    root = args.root.resolve()
    run(root, load_contract(root / "mapping_contract.json"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
