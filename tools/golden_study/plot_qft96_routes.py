#!/usr/bin/env python3
"""Plot validated QFT-96 route hops and write the matching LaTeX table."""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


ROUTES = (
    ("mesh", "xy", "Mesh XY"),
    ("mesh", "yx", "Mesh YX"),
    ("mesh", "shortest_reliable", "Mesh shortest reliable"),
    ("mesh", "max_reliability", "Mesh maximum reliability"),
    ("torus", "dijkstra", "Torus Dijkstra"),
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--latex-output", type=Path, required=True)
    args = parser.parse_args()
    root = args.root.resolve()
    source = root / "validation" / "mapping_audit.csv"
    with source.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    indexed = {(r["topology"], r["route_policy"], int(r["mapping_seed"])): r for r in rows}
    seeds = sorted({int(r["mapping_seed"]) for r in rows})
    if len(rows) != len(ROUTES) * len(seeds) or any(r["valid"] != "True" or r["qubits"] != "96" for r in rows):
        raise ValueError("route audit is incomplete or contains an invalid QFT-96 row")
    if any((topology, policy, seed) not in indexed for topology, policy, _ in ROUTES for seed in seeds):
        raise ValueError("route/seed grid is incomplete")
    figures = root / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(9, 4.8))
    colors = ("#174a7e", "#3f8bc0", "#7aaac5")
    width = 0.23
    for j, seed in enumerate(seeds):
        heights = [int(indexed[(topology, policy, seed)]["physical_hops"]) for topology, policy, _ in ROUTES]
        ax.bar([i + (j - (len(seeds)-1)/2)*width for i in range(len(ROUTES))], heights,
               width=width, label=f"Mapping seed {seed}", color=colors[j % len(colors)])
    ax.set_xticks(range(len(ROUTES)), [label.replace(" ", "\n", 1) for _, _, label in ROUTES])
    ax.set_ylabel("Physical adjacent hops")
    ax.set_ylim(0, max(int(r["physical_hops"]) for r in rows) * 1.15)
    ax.grid(axis="y", alpha=0.25)
    ax.set_axisbelow(True)
    ax.legend(frameon=False, ncol=3, loc="upper left")
    fig.tight_layout()
    png = figures / "qft96_route_hops.png"
    pdf = figures / "qft96_route_hops.pdf"
    fig.savefig(png, dpi=200)
    fig.savefig(pdf)
    plt.close(fig)
    base_url = ("https://github.com/sanjeevkrishnaa/Compiler-Driven-ACE/blob/"
                "codex/ace-scheduler-correctness/results/qft96_2seed_2026-10-26/")
    latex = [
        "% Generated by tools/golden_study/plot_qft96_routes.py; do not edit by hand.",
        "\\begin{figure}[H]", "\\centering",
        "\\includegraphics[width=0.78\\linewidth]{../../../results/qft96_2seed_2026-10-26/figures/qft96_route_hops.pdf}",
        "\\caption{QFT-96 adjacent-hop count on the same T-HQA placement for each seed. Torus uses Dijkstra. These are structural counts, not simulated latency. The complete values are in Table~\\ref{tab:qft96-route-hops} and the \\href{" + base_url + "validation/mapping_audit.csv}{source CSV}.}",
        "\\label{fig:qft96-route-hops}", "\\end{figure}",
        "\\begin{table}[H]", "\\centering\\small",
        "\\begin{tabular}{lrrr}", "\\toprule",
        "Route & Seed 42 hops & Seed 43 hops & Seed 44 hops \\\\", "\\midrule",
    ]
    for topology, policy, label in ROUTES:
        values = [indexed[(topology, policy, seed)]["physical_hops"] for seed in seeds]
        latex.append(f"{label} & " + " & ".join(values) + " \\\\")
    latex.extend([
        "\\bottomrule", "\\end{tabular}",
        "\\caption{Exact QFT-96 route counts for all three mapping seeds. Every row has 1,965 logical migrations and 766 layers. \\href{" + base_url + "validation/mapping_audit.csv}{Source CSV}.}",
        "\\label{tab:qft96-route-hops}", "\\end{table}", "",
    ])
    args.latex_output.parent.mkdir(parents=True, exist_ok=True)
    args.latex_output.write_text("\n".join(latex), encoding="utf-8")
    print(png)
    print(pdf)
    print(args.latex_output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
